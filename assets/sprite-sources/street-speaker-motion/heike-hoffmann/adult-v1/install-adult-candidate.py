"""Install only Heike's checked adult candidate into this isolated worktree.

The integrator reviews and merges this actor; this script never commits or
publishes. Motion delivery is generated by the existing project packer.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import shutil
from pathlib import Path

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[4]
ID="quiz-heike-hoffmann"
BERLIN=ROOT/"assets/sprite-sources/berlin-street-20261022"


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def read(path):return json.loads(Path(path).read_text(encoding="utf8"))
def write(path,data):Path(path).write_bytes((json.dumps(data,ensure_ascii=False,separators=(",",":"))+"\n").encode("utf8"))


def source_provenance():
    path=BERLIN/"provenance.json"
    data=read(path)
    job=read(HERE/"source-generation-receipt.json")["jobs"]
    items={entry["id"]:entry for entry in data["records"]}
    for entry in job:
        source=Path(entry["trackedRawCopy"])
        name=source.stem
        prompt=ROOT/entry["savedRequest"]["file"]
        if sha(prompt)!=entry["savedRequest"]["sha256"] or sha(ROOT/source)!=entry["rawCopySha256"]:
            raise ValueError("Heike generated source or exact prompt changed")
        image=entry["image"]
        components=[value["boundsXYXY"] for value in image["alpha128Components"] if value["alpha128Pixels"]>=100]
        record={"id":name,"prompt":prompt.read_text(encoding="utf8"),
                "role":"Heike adult source attempt; selected use limited to reviewed turn source",
                "file":source.name,"sha256":entry["rawCopySha256"],
                "dimensions":image["dimensions"],"bytes":(ROOT/source).stat().st_size,
                "componentBounds":components,"alphaExtrema":[0,255],
                "runtimeAcceptance":"Source-only paint; family animation requires separate exact native and runtime acceptance.",
                "references":entry["references"],"exactPromptSha256":entry["savedRequest"]["sha256"]}
        if name in items:
            if items[name]!=record:raise ValueError("Conflicting existing Heike provenance id")
        else:
            data["records"].append(record);items[name]=record
    path.write_bytes((json.dumps(data,ensure_ascii=False,indent=2)+"\n").encode("utf8"))


def install(assembly,mouth):
    assembly=Path(assembly);mouth=Path(mouth)
    person=read(assembly/"person-before-mouth.json")
    receipt=read(assembly/"assembly-receipt.json")
    mouth_data=read(mouth/"mouths-v1.json")
    if mouth_data["sources"]!={"standing":receipt["standing"]["sha256"],
                                "desktop":receipt["variants"]["desktop"]["sha256"],
                                "mobile":receipt["variants"]["mobile"]["sha256"]}:
        raise ValueError("Heike mouth source hashes do not match final native cells")
    dest=ROOT/"assets/characters/street-speakers/quiz-heike-hoffmann/delivery-v1"
    dest.mkdir(parents=True,exist_ok=True)
    files={assembly/"standing.webp":ROOT/"assets/characters/street/quiz-heike-hoffmann-standing.webp",
           assembly/"source-desktop.webp":dest/"source-desktop.webp",
           assembly/"source-mobile.webp":dest/"source-mobile.webp",
           mouth/"mouths-v1.json":dest/"mouths-v1.json"}
    for src,target in files.items():
        shutil.copyfile(src,target)
        if sha(src)!=sha(target):raise ValueError("Heike selected bytes differ from candidate")
    person["mouthPaint"]={"file":"./assets/characters/street-speakers/quiz-heike-hoffmann/delivery-v1/mouths-v1.json",
                          "sha256":sha(dest/"mouths-v1.json")}
    manifest_path=ROOT/"assets/characters/street/manifest.json"
    manifest=read(manifest_path)
    old=manifest["characters"][ID]
    if old["id"]!=ID or old["grid"]!=[21,18]:raise ValueError("Wrong existing Heike runtime family")
    manifest["characters"][ID]=person
    write(manifest_path,manifest)
    module=importlib.util.spec_from_file_location("heike_delivery_packer",ROOT/"tools/build-street-motion-delivery.py")
    packer=importlib.util.module_from_spec(module);module.loader.exec_module(packer)
    delivery=dest/"delivery"
    record=packer.run(manifest_path,ID,delivery)
    packer.run(manifest_path,ID,delivery,check=True)
    person["motionDelivery"]={"file":"./assets/characters/street-speakers/quiz-heike-hoffmann/delivery-v1/delivery/motion-delivery.json",
                              "sha256":sha(delivery/"motion-delivery.json")}
    manifest["characters"][ID]=person
    write(manifest_path,manifest)
    source_provenance()
    result={"status":"isolated Heike adult selected candidate; runtime review pending",
            "manifestSha256":sha(manifest_path),"person":person,
            "files":{str(path.relative_to(ROOT)):sha(path) for path in [*files.values(),delivery/"motion-delivery.json",
                    *delivery.glob("*.webp")]},
            "delivery":{"packs":{name:{"grid":pack["grid"],"used":sum(slot is not None for slot in pack["slots"]),
                                        "variants":pack["variants"]} for name,pack in record["packs"].items()}}}
    out=assembly/"installed-receipt.json";out.write_text(json.dumps(result,indent=2)+"\n",encoding="utf8")
    return result


if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--assembly",type=Path,default=ROOT/"output/street-redesign/heike-end-to-end/adult-assembly-candidate")
    parser.add_argument("--mouth",type=Path,default=ROOT/"output/street-redesign/heike-end-to-end/adult-mouth-candidate")
    args=parser.parse_args()
    result=install(args.assembly,args.mouth)
    print(json.dumps({key:result[key] for key in ("status","manifestSha256","delivery")},indent=2))
